    private double calculateIntegralTrapezoidal(double a, double b, double h) {
    if (h <= 0 || a >= b) return 0.0;
    
    double sum = 0.0;
    while (a + h <= b) {
        double y1 = Math.sqrt(a);
        double y2 = Math.sqrt(a + h);
        sum += h * (y1 + y2) / 2.0;
        a += h;
    }
    
    if (a < b) {
        double remainder = b - a;
        double y1 = Math.sqrt(a);
        double y2 = Math.sqrt(b);
        sum += remainder * (y1 + y2) / 2.0;
    }
    return sum;
}
