    private void button3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_button3ActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    int rowCount = model.getRowCount();
    
    for (int i = 0; i < rowCount; i++) {
        try {
            double upper = ((Number) model.getValueAt(i, 0)).doubleValue();
            double lower = ((Number) model.getValueAt(i, 1)).doubleValue();
            double steps = ((Number) model.getValueAt(i, 2)).doubleValue();

            double result = calculateIntegralTrapezoidal(lower, upper, steps);
            model.setValueAt(String.format("%.6f", result), i, 3);
            
        } catch (Exception ex) {
            model.setValueAt("Ошибка", i, 3);
        }
    }
    }//GEN-LAST:event_button3ActionPerformed

